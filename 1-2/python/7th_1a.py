"""시작에 해당하는 정수를 입력받아 변수 s에 대입하고, 끝에 해당하는 정수를
입력받아 e에 대입한 후, for문을 이용하여 start부터 end까지 출력하는
함수print_se(start,end)를 작성하고 호출해보자.(단, 입력한 후 변수 s의 값이 변수 e의
값보다 작을 때 만 함수를 호출한다.)
"""

def print_se(s,e):
    for i in range(s,e+1):
      print(i)

start=int(input("시작: "))
end=int(input("끝: "))

if (start<end):
  print_se(start,end)
else:
  print(f"start({start})값이 end({end})보다 큽니다.")

