"""추가예제1: 임의의 리스트를 매개변수로 입ㄺ받아 리스트 원소의 최대값을반환하는 함수 구현"""

def findMax(l):
  max=l[0]
  for i in l:
    if i>=max:
      max=i
  return max
findMax([1,2,3,4,5])

